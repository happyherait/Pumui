CREATE TABLE app_users (
  id        VARCHAR2(30) PRIMARY KEY,
  name      VARCHAR2(50) NOT NULL,
  dept      VARCHAR2(50) NOT NULL,
  role_code VARCHAR2(30) NOT NULL
);

CREATE TABLE rnd_projects (
  code         VARCHAR2(20) PRIMARY KEY,
  name         VARCHAR2(100) NOT NULL,
  owner_dept   VARCHAR2(50) NOT NULL,
  budget_total NUMBER(15) NOT NULL,
  budget_used  NUMBER(15) DEFAULT 0 NOT NULL,
  end_date     DATE NOT NULL,
  CONSTRAINT ck_budget CHECK (budget_used <= budget_total)
);

CREATE TABLE suppliers (
  code     VARCHAR2(20) PRIMARY KEY,
  name     VARCHAR2(100) NOT NULL,
  approved NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE items (
  code      VARCHAR2(20) PRIMARY KEY,
  name      VARCHAR2(100) NOT NULL,
  category  VARCHAR2(20) NOT NULL,
  unit      VARCHAR2(10) NOT NULL,
  cas_no    VARCHAR2(20),
  strategic NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE regulated_substances (
  cas_no VARCHAR2(20) PRIMARY KEY,
  name   VARCHAR2(100) NOT NULL,
  grade  VARCHAR2(30) NOT NULL
);

CREATE TABLE inventory (
  item_code VARCHAR2(20) NOT NULL REFERENCES items(code),
  location  VARCHAR2(50) NOT NULL,
  quantity  NUMBER(12, 3) NOT NULL,
  PRIMARY KEY (item_code, location)
);

CREATE SEQUENCE pr_seq START WITH 1 NOCACHE;

CREATE TABLE purchase_requests (
  id           NUMBER PRIMARY KEY,
  title        VARCHAR2(200) NOT NULL,
  requester_id VARCHAR2(30) NOT NULL REFERENCES app_users(id),
  status       VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
  head_rev     NUMBER(5) DEFAULT 1 NOT NULL,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_pr_status CHECK (status IN ('OPEN', 'MERGED', 'CLOSED'))
);

CREATE TABLE pr_revisions (
  pr_id        NUMBER NOT NULL REFERENCES purchase_requests(id),
  rev_no       NUMBER(5) NOT NULL,
  content      CLOB NOT NULL,
  content_hash VARCHAR2(64) NOT NULL,
  author_id    VARCHAR2(30) NOT NULL REFERENCES app_users(id),
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  PRIMARY KEY (pr_id, rev_no),
  CONSTRAINT ck_rev_json CHECK (content IS JSON)
);

CREATE TABLE pr_reviews (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pr_id         NUMBER NOT NULL REFERENCES purchase_requests(id),
  reviewer_id   VARCHAR2(30) NOT NULL REFERENCES app_users(id),
  role_code     VARCHAR2(30) NOT NULL,
  decision      VARCHAR2(20) NOT NULL,
  revision_hash VARCHAR2(64) NOT NULL,
  comment_text  VARCHAR2(1000),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_decision CHECK (decision IN ('APPROVED', 'CHANGES_REQUESTED'))
);

CREATE TABLE pr_events (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pr_id      NUMBER NOT NULL REFERENCES purchase_requests(id),
  actor_id   VARCHAR2(30) NOT NULL,
  event_type VARCHAR2(30) NOT NULL,
  detail     VARCHAR2(1000),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE purchase_orders (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pr_id      NUMBER CONSTRAINT uq_order_pr UNIQUE REFERENCES purchase_requests(id),
  item_code  VARCHAR2(20) REFERENCES items(code),
  supplier   VARCHAR2(20) REFERENCES suppliers(code),
  quantity   NUMBER(12, 3) NOT NULL,
  unit_price NUMBER(15) NOT NULL,
  amount     NUMBER(15) NOT NULL,
  ordered_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_orders_item ON purchase_orders (item_code, ordered_at);
CREATE INDEX ix_events_pr ON pr_events (pr_id, id);
CREATE INDEX ix_reviews_pr ON pr_reviews (pr_id, id);

CREATE OR REPLACE TRIGGER trg_revisions_immutable
BEFORE UPDATE OR DELETE ON pr_revisions
BEGIN
  RAISE_APPLICATION_ERROR(-20001, 'pr_revisions is append-only');
END;
/

CREATE OR REPLACE TRIGGER trg_reviews_immutable
BEFORE UPDATE OR DELETE ON pr_reviews
BEGIN
  RAISE_APPLICATION_ERROR(-20002, 'pr_reviews is append-only');
END;
/

CREATE OR REPLACE TRIGGER trg_events_immutable
BEFORE UPDATE OR DELETE ON pr_events
BEGIN
  RAISE_APPLICATION_ERROR(-20003, 'pr_events is append-only');
END;
/
